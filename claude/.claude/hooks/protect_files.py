#!/usr/bin/env python3
"""PreToolUse hook (matcher: Write|Edit|MultiEdit|NotebookEdit).

Blocks edits to files that should not be changed by hand or by an agent:
  - .env and .env.* (but .env.example, .env.sample, .env.template and .env.dist are allowed)
  - anything inside a .git directory (.github and .gitignore are fine)
  - lock files such as package-lock.json, uv.lock, poetry.lock, Cargo.lock, go.sum
  - key and certificate stores: *.pem, *.key, *.p12, *.pfx, and private SSH keys
    (id_rsa, id_dsa, id_ecdsa, id_ed25519; the .pub files are allowed)
  - credential files: .netrc, .pgpass, and .aws/credentials

Exit code 2 blocks the call and sends stderr to Claude so it can change course.

Limit: this only covers the edit tools. A shell command such as `echo x > .env`
is not caught, so keep the Read(.env*) deny rule in settings.json as well.
"""
import json
import os
import re
import sys

ALLOWED_ENV_SUFFIXES = {"example", "sample", "template", "dist"}
LOCK_FILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock",
    "Pipfile.lock", "Cargo.lock", "go.sum", "composer.lock", "Gemfile.lock",
}
KEY_SUFFIXES = (".pem", ".key", ".p12", ".pfx")
CREDENTIAL_NAMES = {".netrc", ".pgpass"}


def reason_protected(path):
    norm = os.path.normpath(path)
    parts = norm.replace("\\", "/").split("/")
    name = parts[-1]

    if ".git" in parts[:-1] or name == ".git":
        return "it is inside a .git directory"
    if name == ".env" or (name.startswith(".env.") and name.rsplit(".", 1)[-1] not in ALLOWED_ENV_SUFFIXES):
        return "it is an environment file that usually holds secrets"
    if name in LOCK_FILES:
        return "lock files should be regenerated by the package manager, not edited"
    if name.endswith(KEY_SUFFIXES) or re.fullmatch(r"id_(rsa|dsa|ecdsa|ed25519)", name):
        return "it is a private key or certificate store"
    if name in CREDENTIAL_NAMES or (name == "credentials" and ".aws" in parts[:-1]):
        return "it is a credentials file"
    return None


def main():
    try:
        data = json.load(sys.stdin)
    except json.JSONDecodeError:
        return
    tool_input = data.get("tool_input") or {}
    path = tool_input.get("file_path") or tool_input.get("notebook_path") or tool_input.get("path")
    if not isinstance(path, str) or not path:
        return
    reason = reason_protected(path)
    if reason:
        print(
            f"Blocked: {path} is protected ({reason}). "
            "Ask the user to make this change, or to adjust protect_files.py.",
            file=sys.stderr,
        )
        sys.exit(2)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # fail open; SystemExit from sys.exit(2) is not caught here
        print(f"protect_files.py error (edit allowed): {exc}", file=sys.stderr)
